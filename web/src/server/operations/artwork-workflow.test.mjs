import { test } from 'node:test'
import assert from 'node:assert/strict'
import { artworkStep } from './artwork-workflow.ts'
const initial = { id: 'jobabcdefghijk', ownerId: 'ownerabcdefghij', photoKey: 'captureabcdefgh', sourceFileId: 'sourceabcdefgh', artId: 'artabcdefghijk', phase: 'reserved', revision: 'r0' }
const fileId = 'outputabcdefgh'
function fixture(patch = {}) {
  let row = { ...initial, ...patch }, revision = 0
  const seen = { generated: 0, stored: 0, published: 0, narrowed: 0, public: false }
  let allowed = true, premium = true
  const copy = () => structuredClone(row)
  const replace = (before, phase, outputFileId = before.outputFileId) => {
    assert.equal(row.revision, before.revision, 'persisted CAS rejects a stale writer')
    assert.equal(row.phase, before.phase)
    row = { ...row, phase, revision: `r${++revision}`, ...(outputFileId ? { outputFileId } : {}) }
    return copy()
  }
  const ports = {
    load: async id => id === row.id ? copy() : null,
    access: async () => ({ allowed, premium }),
    claim: async (before, phase) => row.revision === before.revision ? replace(before, phase) : null,
    keep: async (before, phase, file) => replace(before, phase, file),
    generate: async () => { seen.generated++; return new Uint8Array([1, 2, 3]) },
    storePrivate: async () => { seen.stored++; assert.equal(seen.public, false); return fileId },
    publishSlice: async () => { seen.published++; seen.public = true; return true },
    narrow: async () => { seen.narrowed++; seen.public = false },
  }
  return { ports, seen, row: copy, allowed: value => { allowed = value }, premium: value => { premium = value },
    step: () => artworkStep(ports, initial.ownerId, initial.id) }
}
test('generated bytes stay private until publication; successful phases and ready retries draw once', async () => {
  const f = fixture()
  assert.equal((await f.step()).state, 'continue')
  assert.equal(f.row().phase, 'stored'); assert.equal(f.seen.public, false)
  assert.equal((await f.step()).state, 'continue')
  assert.equal(f.row().phase, 'publishing'); assert.equal(f.seen.public, false)
  assert.equal((await f.step()).state, 'ready')
  assert.equal((await f.step()).state, 'ready')
  assert.equal(f.seen.generated, 1); assert.equal(f.seen.published, 1)
})
test('signed-out/foreign jobs refuse before provider work', async () => {
  const f = fixture()
  for (const actor of [null, 'otherabcdefghij']) await assert.rejects(artworkStep(f.ports, actor, initial.id))
  await assert.rejects(artworkStep(f.ports, initial.ownerId, '../job'))
  assert.equal(f.seen.generated, 0)
})
test('free users and eligibility lost after the source claim never reach generation', async () => {
  const free = fixture(); free.premium(false)
  await assert.rejects(free.step()); assert.equal(free.seen.generated, 0)
  const expired=fixture(),claim=expired.ports.claim
  expired.ports.claim=async(...args)=>{const result=await claim(...args);expired.premium(false);return result}
  assert.equal((await expired.step()).state,'recovery');assert.equal(expired.seen.generated,0)
})
test('a source hold or unreadable ownership prevents drawing and narrows old access', async () => {
  const f = fixture(); f.allowed(false)
  assert.equal((await f.step()).state, 'held')
  assert.equal(f.seen.generated, 0); assert.equal(f.seen.narrowed, 1)
})
test('a concurrent execution cannot win the generation claim twice', async () => {
  const f = fixture()
  let release, began
  const started = new Promise(resolve => { began = resolve })
  const pending = new Promise(resolve => { release = resolve })
  f.ports.generate = async () => { f.seen.generated++; began(); await pending; return new Uint8Array([1]) }
  const first = f.step(); await started
  assert.equal((await f.step()).state, 'pending'); assert.equal(f.seen.generated, 1)
  release(); await first
  assert.equal(f.row().phase, 'stored')
})
test('an ambiguous provider or upload failure never automatically redraws', async () => {
  for (const stage of ['generate', 'storePrivate']) {
    const f = fixture()
    f.ports[stage] = async () => { if (stage === 'generate') f.seen.generated++; throw Error('lost response') }
    await assert.rejects(f.step()); assert.equal(f.row().phase, 'recovery')
    assert.equal((await f.step()).state, 'recovery'); assert.equal(f.seen.generated, 1)
  }
})
test('a persisted generation claim remains stopped even when recovery persistence fails', async () => {
  const f = fixture()
  f.ports.generate = async () => { f.seen.generated++; throw Error('timeout') }
  f.ports.keep = async () => { throw Error('storage unavailable') }
  await assert.rejects(f.step())
  assert.equal(f.row().phase, 'generating'); assert.equal((await f.step()).state, 'pending')
  assert.equal(f.seen.generated, 1)
})
test('a source hold after storing or during publication wins and compensates', async () => {
  const f = fixture(); await f.step(); f.allowed(false)
  assert.equal((await f.step()).state, 'held'); assert.equal(f.seen.public, false)
  const race = fixture(); await race.step(); await race.step()
  race.ports.publishSlice = async () => { race.seen.public = true; race.allowed(false); return true }
  assert.equal((await race.step()).state, 'held'); assert.equal(race.seen.public, false)
})
test('partial publication/final persistence failures narrow, and bounded retries reuse output', async () => {
  const f = fixture(); await f.step(); await f.step()
  f.ports.publishSlice = async () => { f.seen.public = true; throw Error('grant write failed') }
  await assert.rejects(f.step()); assert.equal(f.seen.public, false); assert.equal(f.row().phase, 'publishing')
  let calls = 0
  f.ports.publishSlice = async () => ++calls > 1
  assert.equal((await f.step()).state, 'continue'); assert.equal((await f.step()).state, 'ready')
  assert.equal(f.seen.generated, 1)
  const failed = fixture(); await failed.step(); await failed.step()
  const keep = failed.ports.keep
  failed.ports.keep = async (job, phase, file) => { if (phase === 'ready') throw Error('final write failed'); return keep(job, phase, file) }
  await assert.rejects(failed.step()); assert.equal(failed.seen.public, false)
})
test('a ready cache entry held later is narrowed and stops reporting ready', async () => {
  const f = fixture(); await f.step(); await f.step(); await f.step(); f.allowed(false)
  assert.equal((await f.step()).state, 'held'); assert.equal(f.seen.public, false)
  assert.equal(f.seen.generated, 1)
})
test('held publication drains multiple grant slices before reporting a terminal state', async () => {
  const f = fixture({phase: 'publishing', outputFileId: fileId})
  f.allowed(false)
  let slices = 0
  f.ports.narrow = async () => { f.seen.public = false; return ++slices === 3 }
  assert.equal((await f.step()).state, 'continue')
  assert.equal((await f.step()).state, 'continue')
  assert.equal((await f.step()).state, 'held')
  assert.equal(f.seen.generated, 0)
})
test('a hold arriving inside publication drains compensation before committing held', async () => {
  const f = fixture({phase: 'publishing', outputFileId: fileId})
  f.ports.publishSlice = async () => { f.allowed(false); return true }
  let slices = 0
  f.ports.narrow = async () => ++slices > 1
  assert.equal((await f.step()).state, 'continue')
  assert.equal(f.row().phase, 'publishing')
  assert.equal((await f.step()).state, 'held')
  assert.equal(f.seen.generated, 0)
})
test('corrupt stored output or a changed canonical claim is refused without spending', async () => {
  for (const patch of [{ phase: 'stored' }, { outputFileId: '../file' }, { ownerId: 'otherabcdefghij' }]) {
    const f = fixture(patch); await assert.rejects(f.step()); assert.equal(f.seen.generated, 0)
  }
  const f = fixture(); f.ports.claim = async job => ({ ...job, phase: 'generating', revision: 'r1', photoKey: 'anothercaptureab' })
  await assert.rejects(f.step()); assert.equal(f.seen.generated, 0)
})

